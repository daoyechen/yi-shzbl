def norm_fang(n):
    n = n.replace("方", "")
    for a, b in FANG_NORM.items():
        n = n.replace(a, b)
    return n


def edit1(a, b):
    if abs(len(a) - len(b)) > 1:
        return False
    if a == b:
        return True
    if len(a) == len(b):
        return sum(x != y for x, y in zip(a, b)) <= 1
    if len(a) > len(b):
        a, b = b, a
    for i in range(len(b)):
        if b[:i] + b[i + 1:] == a:
            return True
    return False


