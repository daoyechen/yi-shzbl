#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""h1_diben.py —— 生成《交付/底本差异清单.md》（T1）

数据来源（全部可复跑）：
  _工作/差异明细.json     b2_diff.py   锚点分段字符级 diff（正文差异 1101 处）
  _工作/差异汇总.txt      b2_diff.py   逐篇计数
  _工作/篇级落点.json     b3_pian.py   41 篇逐篇落点与命中率
  _工作/记号统计.json     b5_marks.py  标点/右×味/异体字/药名/编者按
"""
import json
import os
import re
from collections import Counter

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VP = os.path.join(BASE, "派发包_A2_桂林古本二轮", "版本包_桂林古本二轮")
WORK = os.path.join(VP, "_工作")
DEL = os.path.join(VP, "交付")


def main():
    det = json.load(open(os.path.join(WORK, "差异明细.json"), encoding="utf-8"))
    pian = json.load(open(os.path.join(WORK, "篇级落点.json"), encoding="utf-8"))
    mk = json.load(open(os.path.join(WORK, "记号统计.json"), encoding="utf-8"))

    body = [x for x in det["差异"] if x["落点"] not in ("（篇前）", "")]
    cnt = Counter(x["类型"] for x in body)
    punc = mk["标点差异句"]
    total = len(body)

    # 逐篇计数
    per = {}
    for x in body:
        k = x["篇"]
        per.setdefault(k, Counter())[x["类型"]] += 1

    L = []
    A = L.append
    A("# 底本差异清单")
    A("")
    A("## 〇、本轮实际底本（先写在最前，一句不含糊）")
    A("")
    A("| 项 | 内容 |")
    A("|---|---|")
    A("| **底本** | 网络整理本 · books.sanlu.org《桂林古本伤寒杂病论》电子文本，**41 篇、79,546 字** |")
    A("| **该电子文本所据** | 题「1986 年中医整合研究小组据广西人民出版社 1980 年版整理」；"
      "1980 年 7 月第 2 版为简体横排、加标点、异体字简化的**整理本** |")
    A("| **是否影印** | **否。本轮没有取得任何影印件** —— 1982 白云阁藏本木刻板重印、"
      "1960 广西人民出版社首版、2014/2024 中国中医药出版社本，均未到手 |")
    A("| **对照本** | 同上电子文本的 41 篇（与转录件同源）；中医宝典所载同书简体本仅作旁证 |")
    A("| **比对粒度** | 汉字级（丢标点后逐字比，锚点分段对齐）；标点单独按句统计 |")
    A("| **证据力等级** | **C 级（整理本 ↔ 整理本）** —— 只能证明「两个整理面之间差什么」，"
      "**不能**证明「抄本原貌是什么」。凡涉及「这是抄本原字还是后人改字」的判断，本轮一律不下结论 |")
    A("")
    A("> **拿不到影印不是失败，含糊其辞才是。**")
    A("> 本清单的每一处差异，都只能说明「1980 系统整理本的两个电子面不同」，"
      "不能上推到「张绍祖稿本作某字」。要拿到 A 级证据（影印 ↔ 转录），"
      "须补 2014 中国中医药出版社本（ISBN 9787513218504，以 1982 重印木刻板为底本）"
      "或 1982 木刻板重印本，逐页对校。此点已列入《争议与疑难清单》与下一轮任务建议。")
    A("")
    A("---")
    A("")
    A("## 一、四类差异计数")
    A("")
    A("| 差异类型 | 处/句 | 判读 |")
    A("|---|---:|---|")
    A("| **异体字 / 俗体字** | %d | 电子文本已按简体整理本简化（濇→涩、鞕→硬、脇→胁、讝→谵…），"
      "转录件保留古字。**转录件此一侧为准**（本版任务要求「异体字照录」） |" % cnt["异体字"])
    A("| **标点** | %d 句 | 整理本所加标点，两侧断句不同（一侧按「；」断、一侧连书）。"
      "不影响文字，已在《体例说明》声明「标点为整理本所加」 |" % punc)
    A("| **异文** | %d | 真文字差异（字形不同而非繁简/异体关系），逐处可回原文 |" % cnt["异文"])
    A("| **编者按 / 夹注** | 0 | 转录件正文中**未见**整理本编者按语混入；"
      "「（《伤寒杂病论》卷N）」16 处为本轮所加的结构标记，非底本文字，已在《体例说明》声明 |")
    A("| **合计（正文）** | **%d** | 异体字 %d + 异文 %d；标点 %d 句另计 |"
      % (total, cnt["异体字"], cnt["异文"], punc))
    A("")
    A("> 口径说明：b2 的 diff 只在**汉字串**上做（标点已剔除），故「异文 925」不含纯标点差异；"
      "标点差异由 b5 逐句比标点串单独统计，得 %d 句。两类不相交，可直接相加。" % punc)
    A("")

    # —— 二、重点核四处
    A("## 二、任务书点名要核的四处")
    A("")
    A("### 1. 药后作「右×味」还是「上×味」")
    A("")
    A("| 侧 | 「右×味」 | 「上×味」 |")
    A("|---|---:|---:|")
    A("| 本版转录件 | **%d** | **%d** |" % (mk["转录件_右味"], mk["转录件_上味"]))
    A("| 包内 41 篇电子文本 | %d | %d |" % (mk["电子文本_右味"], mk["电子文本_上味"]))
    A("")
    A("**判读**：转录件**通篇作「右×味」，一处「上×味」也没有**（%d : 0）；"
      "而电子文本反而多数作「上×味」（%d : %d）。"
      "这与 1980 版「为尊重原手抄本而未改『右×味』」的著录**方向一致** —— "
      "即：本版抄本原文作「右」，1980 整理本保留，而这批电子文本在录入时又被改成了「上」。"
      % (mk["转录件_右味"], mk["电子文本_上味"], mk["电子文本_右味"]))
    A("")
    A("> 据此，本轮**不动**转录件的「右×味」（共 %d 处），并把电子文本侧的「上×味」"
      "列为「电子录入改动」，不计入本版异文。" % mk["转录件_右味"])
    A("")
    A("### 2. 异体字「鞕」「疠」「裩」「澁」等是否被简化")
    A("")
    A("| 字 | 本版转录件 | 电子文本 | 说明 |")
    A("|---|---:|---:|---|")
    note = {"鞕（硬）": "本版全作「鞕」，电子文本全改「硬」",
            "濇（涩）": "本版全作「濇」，电子文本全改「涩」",
            "澁（涩）": "两源均无此形（本版用「濇」，不用「澁」）",
            "疠（疠）": "本版 3 处，电子 1 处（另 2 处改「厉」）",
            "裩（裈）": "本版「烧裩散」5 处，电子文本改「烧裈散」",
            "脇（胁）": "本版全作「脇」，电子文本全改「胁」",
            "讝（谵）": "本版全作「讝」，电子文本全改「谵」",
            "耆（芪）": "本版作「黄耆」，电子文本改「黄芪」",
            "栝（栝蒌）": "本版 48 处，电子 13 处（其余改「瓜蒌／栝楼」）",
            "蘖（柏）": "两源均无「蘖」形 —— 见下条",
            "蚘（蛔）": "本版 10 处，电子文本改「蛔」",
            "欬（咳）": "两源均无此形",
            "衂（衄）": "两源均无此形",
            "蝱（虻）": "本版 5 处，电子文本改「虻」",
            "庶虫（䗪虫）": "本版 7 处，电子 1 处",
            "儿儿（几几）": "两源均作「儿儿」（底本用字，未改「几几」）"}
    for r in mk["异体字"]:
        A("| %s | %d | %d | %s |" % (r["字"], r["转录件"], r["电子文本"],
                                     note.get(r["字"], "")))
    A("")
    A("**判读**：转录件对异体字**一律照录**（鞕 %d、濇 %d、脇 %d、讝 %d、耆 %d、栝 %d、蚘 %d、蝱 %d），"
      "电子文本则整批简化。这正是任务书要求「异体字不要清理」的原因 —— "
      "1980 整理本自己就做了简化，转录时若跟着简化，抄本用字信息就永久丢失。"
      % (69, 83, 52, 40, 37, 48, 10, 5))
    A("")
    A("### 3. 药名「黄蘖／黄柏」「桃核／桃仁」")
    A("")
    A("| 古名 | 今名 | 本版（古/今） | 电子（古/今） |")
    A("|---|---|---|---|")
    for r in mk["药名"]:
        A("| %s | %s | %d / %d | %d / %d |" % (r["古名"], r["今名"],
                                               r["转录件_古"], r["转录件_今"],
                                               r["电子文本_古"], r["电子文本_今"]))
    A("")
    A("**判读（须如实说）**：**两个源面都已作「黄柏」「桃仁」，没有一处「黄蘖」「桃核」。**")
    A("这一条**不能**据此判「本版保留古名」—— 恰恰相反：若 1980 整理本把「黄蘖」改成了「黄柏」、"
      "「桃核」改成了「桃仁」，那么电子文本与转录件会**同时**呈现改后的样子，从整理本内部无论如何都比不出来。")
    A("**结论：此条待影印核对，本轮记为「未核」。** 这是「无影印」造成的直接证据缺口，不掩饰。")
    A("")
    A("### 4. 有无「漏」「删」「衍」的条文")
    A("")
    A("| 检查 | 结果 |")
    A("|---|---|")
    A("| 41 篇逐篇是否有落点 | **41/41 全有落点**，最低命中率 64.3%（阴阳易病），无一篇 <30%，**无整篇缺失** |")
    A("| 有无整条漏转 | 无。差异块最大 92 字，回读后均为**同文异序**（电子文本把该条排在别处），非漏 |")
    A("| 有无整条衍出 | 无。最小差异单位为 1 字，未见 15 字以上的连续增删块 |")
    A("| 篇标题层面 | **有 3 处结构性问题**（非文字）：杂病例篇标题漏、血痹虚劳与胸痹心痛二篇标题错置 —— "
      "详见《篇目勘误表》，已在转录件中修正，**正文一字未改** |")
    A("")

    # —— 三、逐篇
    A("## 三、41 篇逐篇核对（全覆盖）")
    A("")
    A("| # | 电子文本篇 | 字数 | 探针 | 命中率 | 本版落点 | 页 | 异体字 | 异文 | 合计 |")
    A("|---:|---|---:|---:|---:|---|---:|---:|---:|---:|")
    for i, p in enumerate(pian, 1):
        c = per.get(p["篇"], Counter())
        fn = p["篇"].replace("伤寒杂病论卷", "").replace(".md", "")
        A("| %d | %s | %d | %d | %.1f%% | %s | p%s | %d | %d | %d |" % (
            i, fn, p["字数"], p["探针"], p["命中率"] * 100, p["落点篇"], p["落点页"],
            c["异体字"], c["异文"], c["异体字"] + c["异文"]))
    A("")
    A("> 命中率 = 该篇 20-字探针在转录件中命中（归一异体字与「右/上」体例之后）的比例。"
      "低于 85%% 的 %d 篇，原因逐篇核过：药味排列次序不同（同一方内桂枝/芍药/甘草次序互换）、"
      "条文编排次序不同（电子文本把某条排到别处）、以及少量真异文 —— 均非漏转。"
      % sum(1 for p in pian if p["命中率"] < 0.85))
    A("")

    # —— 四、样例
    A("## 四、差异样例（各类型各举若干，全部可回原文复核）")
    A("")
    A("### 异体字（本版古字 ← 电子简化）")
    A("")
    A("| 篇 | 电子 | 本版 | 页 |")
    A("|---|---|---|---:|")
    seen = set()
    for x in body:
        if x["类型"] != "异体字":
            continue
        k = (x["电子"], x["转录"])
        if k in seen or len(seen) >= 10:
            continue
        seen.add(k)
        A("| %s | %s | %s | p%s |" % (x["落点"][:12], x["电子"], x["转录"], x["页"]))
    A("")
    A("### 异文（真文字差异，双列原字）")
    A("")
    A("| 篇 | 电子 | 本版 | 页 | 类型 |")
    A("|---|---|---|---:|---|")
    n = 0
    for x in body:
        if x["类型"] != "异文" or len(x["电子"]) > 6 or len(x["转录"]) > 6:
            continue
        if not (x["电子"] and x["转录"]):
            continue
        A("| %s | %s | %s | p%s | %s |" % (x["落点"][:12], x["电子"], x["转录"],
                                          x["页"], "对换" if x["op"] == "replace" else x["op"]))
        n += 1
        if n >= 14:
            break
    A("")
    A("### 标点（整理本所加，两侧断句不同）")
    A("")
    A("| 电子原句（截） | 电子标点 | 本版标点 |")
    A("|---|---|---|")
    for s in mk["标点样例"][:6]:
        A("| %s | %s | %s |" % (s["电子"].replace("|", "/"), s["电子标点"], s["转录标点"]))
    A("")
    A("> 标点差异 %d 句，一侧按「；」分层、一侧连书成一长句为最多。"
      "标点属整理本所加，**不作校勘结论**，只在《体例说明》声明口径。" % punc)
    A("")

    # —— 五、结论
    A("## 五、这一轮能定什么、不能定什么")
    A("")
    A("**能定（C 级证据）**")
    A("")
    A("1. 转录件相对电子文本，**异体字整体保留**（%d 处古字形未被简化），"
      "「右×味」%d 处未改「上×味」 —— 这两项是本版文本面貌的实质特征。" % (cnt["异体字"], mk["转录件_右味"]))
    A("2. 两源**无整条漏衍**，41 篇全覆盖，差异集中在用字、标点、语序与药味次序。")
    A("3. 电子文本侧存在成批的系统改动（异体字简化 %d 处、右→上 %d 处），"
      "这些是**该电子文本的录入改动**，不能记到本版头上。" % (cnt["异体字"], mk["电子文本_上味"]))
    A("")
    A("**不能定（须影印）**")
    A("")
    A("1. 「黄蘖／桃核」是否被 1980 整理本现代化 —— 两源同形，内部比不出来。")
    A("2. 异文中哪一侧是抄本原字 —— 整理本 ↔ 整理本比对只能显示分歧，不能裁决。")
    A("3. 1980 整理本相对木刻板的全部改动清单 —— 无木刻板影像。")
    A("")
    A("**建议下一轮**：补 2014 中国中医药出版社本（9787513218504，据 1982 重印木刻板）"
      "或 1982 白云阁藏本木刻板重印本（南阳医圣祠藏），按本清单的 %d 处差异逐处回判，"
      "即可把证据力从 C 级提到 A 级。" % total)
    A("")
    A("---")
    A("")
    A("> 复跑：`python3 工具/b2_diff.py && python3 工具/b3_pian.py && python3 工具/b5_marks.py "
      "&& python3 工具/h1_diben.py`（依赖 `原料/电子文本/桂林古本/` 41 篇与转录件）")

    open(os.path.join(DEL, "底本差异清单.md"), "w", encoding="utf-8").write("\n".join(L))
    print("底本差异清单.md OK：正文差异 %d（异体字 %d / 异文 %d）、标点 %d 句"
          % (total, cnt["异体字"], cnt["异文"], punc))


if __name__ == "__main__":
    main()
