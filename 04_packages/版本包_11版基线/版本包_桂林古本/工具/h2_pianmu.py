def load_title():
    p = os.path.join(BASE, "派发包_A2_桂林古本二轮", "原料", "电子文本", "桂林古本",
                     "_目录.json")
    for it in json.load(open(p, encoding="utf-8")):
        _TITLE[it["file"]] = it["title"]


def short(fn):
    """电子文本文件名 → 篇名（优先用 _目录.json 的原始标题）"""
    t = _TITLE.get(fn)
    if t:
        parts = re.split(r"\s+", t.strip())
        s = parts[-1] if len(parts) > 1 else t
        return s.replace("（上）", "上").replace("（下）", "下")
    s = fn.replace(".md", "")
    s = re.sub(r"^\d+_伤寒杂病论", "", s)
    s = re.sub(r"^卷(?:第)?[一二三四五六七八九十]+", "", s)
    return s


def norm(s):
    """只留篇名的辨识主干：去「辨／病／脉证并治／第X／上／下」与卷次"""
    s = re.sub(r"脉证并治.*$", "", s)
    s = re.sub(r"[辨病第上下一二三四五六七八九十]", "", s)
    return s


