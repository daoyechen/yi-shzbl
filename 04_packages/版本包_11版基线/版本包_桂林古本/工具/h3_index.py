TITLE = {}


def short(fn):
    t = TITLE.get(fn, fn)
    parts = re.split(r"\s+", t.strip())
    return (parts[-1] if len(parts) > 1 else t).replace("（上）", "上").replace("（下）", "下")


SUB = {"下利", "呕吐哕", "寒疝", "消渴", "阴阳易病", "狐惑病", "阳毒阴毒",
       "水饮病", "厉节病", "疮痈病", "新产病", "妇人病"}


def _norm(s):
    s = re.sub(r"脉证并治.*$", "", s)
    return re.sub(r"[辨病第上下一二三四五六七八九十]", "", s)


def indep(p):
    sh = short(p["篇"])
    if sh in SUB:
        return False
    a, b = _norm(sh), _norm(p["落点篇"])
    return bool(a and b) and (a == b or (len(a) >= 2 and (b.startswith(a) or a.startswith(b))))


