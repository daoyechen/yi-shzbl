def han(s):
    return "".join(c for c in s if "\u4e00" <= c <= "\u9fff")


def pick_span(line, anchor, target):
    """长行（连抄数条）中取出与宋本对应的句窗：
    按「。；」切句，从含 anchor 的句子起，向两侧扩展取与 target 最相似的一段连续句窗。"""
    if len(han(line)) <= len(han(target)) * 1.5:
        return line
    sents = re.findall(r"[^。；]*[。；]?", line)
    sents = [s for s in sents if s]
    i0 = next((i for i, s in enumerate(sents) if anchor in s), None)
    if i0 is None:
        return line
    t = han(target)
    best, bj, bk, blen = -1, i0, i0, 10 ** 9
    for j in range(0, i0 + 1):
        for k in range(i0, len(sents)):
            span = han("".join(sents[j:k + 1]))
            r = difflib.SequenceMatcher(None, t, span, autojunk=False).ratio()
            # 相似度相近时取更短的句窗（避免把邻条带进来）
            if r > best + 0.005 or (r >= best - 0.005 and len(span) < blen):
                best, bj, bk, blen = r, j, k, len(span)
    return "".join(sents[bj:bk + 1]).strip()


def main():
    raw = open(TXT, encoding="utf-8").read()
    lines = [l.strip() for l in raw.split("\n")]
    marks = [(i, int(m.group(1))) for i, l in enumerate(lines)
             if (m := re.match(r"<!-- p(\d+) -->", l))]
    heads = [(i, l[3:]) for i, l in enumerate(lines) if l.startswith("## ")]

    def page_of(k):
        pg = None
        for i, p in marks:
            if i <= k:
                pg = p
        return pg

    def pian_of(k):
        r = ""
        for i, h in heads:
            if i <= k:
                r = h
        return r

    cand = {c["条号"]: c for c in json.load(
        open(os.path.join(WORK, "T4候选.json"), encoding="utf-8"))}
    eng = json.load(open(DEL, encoding="utf-8"))
    todo = [e for e in eng["条目"] if e["状态"] != "有"]

    items, unresolved = [], []
    for e in todo:
        no = e["条号"]
        if no not in NOTE:
            unresolved.append(no)
            continue
        conf, why = NOTE[no]
        if conf == "—":                    # 判「无」：不取本版原文，只用证据
            items.append({
                "条号": no, "状态": "无",
                "差异类型": "此版正文无此条", "相似": 0.0,
                "依据": why, "原因": "体例不同", "证据": why,
                "分段": [],
            })
            continue
        # 本版落点：优先取「条文行」——排掉方名行、药味行、煎服法行、篇标题
        def bad(t):
            if not t or t.startswith("#") or t.startswith("<!--"):
                return True
            if re.fullmatch(r"[^\s]{2,20}方", t):
                return True
            if re.match(r"^(右|上)[一二三四五六七八九十百]+味", t):
                return True
            if "\u3000" in t and len(han(t)) < 60:
                return True
            return False

        # 落点以人工核定的「本版关键短语」定位（相似度会被邻条带偏）
        key = ANCHOR.get(no, "")
        k, txt = None, ""
        if key:
            for i, l in enumerate(lines):
                if key in l:
                    k, txt = i, l
                    break
        if k is None:
            cs = sorted(cand[no]["候选"], key=lambda c: -c["相似"])
            k = cs[0]["行"] - 1
            txt = lines[k]
        if key:
            txt = pick_span(txt, key, e["宋本"])
        # 差异
        a, b = han(e["宋本"]), han(txt)
        sm = difflib.SequenceMatcher(None, a, b, autojunk=False)
        r = sm.ratio()
        types = []
        if a == b:
            types = ["同文"]
        else:
            if r >= 0.95:
                types = ["省文"]
            elif r >= 0.8:
                types = ["异文"]
            else:
                types = ["体例归并"]
            if re.search(r"〔方|\[方|用前第", e["宋本"]):
                types.append("（宋本方后注本版无）")
        items.append({
            "条号": no, "状态": "有", "置信": conf,
            "原文": txt, "页": page_of(k), "篇": pian_of(k),
            "差异类型": "、".join(types), "相似": round(r, 3),
            "依据": "%s；本版 p%s「%s」（相似 %.2f）" % (why, page_of(k), txt[:60], r),
            "原因": "", "证据": "",
            "分段": [{"置信": conf, "页": page_of(k), "原文": txt}],
        })
    print("裁定 %d 条；未定 %d 条 %s" % (len(items), len(unresolved), unresolved))
    json.dump({"条目": items, "说明": "T4：34 条「暂未匹配」+ 2 条「体例不同」逐条定性"},
              open(os.path.join(VP, "交付", "人工裁定.json"), "w", encoding="utf-8"),
              ensure_ascii=False, indent=1)
    for it in items:
        print("%3d %s %s p%s %s" % (it["条号"], it["置信"], it["差异类型"],
                                    it["页"], it["原文"][:48]))


if __name__ == "__main__":
    main()
