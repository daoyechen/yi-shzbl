#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""i1_anchor.py —— 生成《交付/锚点表.md》

本版（桂林古本）编者校记中没有「同《宋本伤寒论》第X条」式硬锚点，
旧版锚点表因此只有一句「(本版无…硬锚点)」，等于空表。
本轮 T4 把 36 条逐条核定，每条都指定了本版明文落句 —— 这 36 条即本包的
**人工落点锚**，证据力 C 级（据整理本正文核，未见影印）。

表内四栏是一次判定的完整链条：
  宋本条目 → 锚句（本轮据以定位的本版句子）→ 本版落点原文 → 页/行/篇
"""
import json
import os
import re

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VP = os.path.join(BASE, "派发包_A2_桂林古本二轮", "版本包_桂林古本二轮")
TXT = os.path.join(VP, "版本正文", "01_桂林古本伤寒杂病论.md")
JUD = os.path.join(VP, "交付", "人工裁定.json")
OUT = os.path.join(VP, "交付", "锚点表.md")

import importlib.util
spec = importlib.util.spec_from_file_location(
    "f1", os.path.join(BASE, "工具", "f1_decide.py"))

# 直接解析 ANCHOR 字典（避免 import 触发 f1_decide 的写盘副作用）
src = open(os.path.join(BASE, "工具", "f1_decide.py"), encoding="utf-8").read()
blk = re.search(r"^ANCHOR = \{(.*?)^\}", src, re.S | re.M).group(1)
ANCHOR = {}
for m in re.finditer(r'(\d+):\s*"([^"]*)"', blk):
    ANCHOR[int(m.group(1))] = m.group(2)

lines = open(TXT, encoding="utf-8").read().split("\n")
J = json.load(open(JUD, encoding="utf-8"))["条目"]
J.sort(key=lambda x: x["条号"])


def lineno(text):
    """本版正文中该句所在行号（1 基）；取首个命中。"""
    core = text.strip().rstrip("。；")
    if not core:
        return 0
    for i, l in enumerate(lines, 1):
        if core in l:
            return i
    # 退一步：取前 12 字
    k = core[:12]
    for i, l in enumerate(lines, 1):
        if k and k in l:
            return i
    return 0


def esc(s):
    return s.replace("|", "\\|")


rows = []
for x in J:
    no = x["条号"]
    if x["状态"] == "无":
        rows.append((no, "无", "—", esc(ANCHOR.get(no, "")), "**本版正文无此句**",
                     "—", "—", "0"))
    else:
        pg = x.get("页", "")
        rows.append((no, "有", x.get("置信", ""), esc(ANCHOR.get(no, "")),
                     esc(x.get("原文", "")), pg, x.get("篇", ""),
                     "%.2f" % x.get("相似", 0)))

yes = [r for r in rows if r[1] == "有"]
no_ = [r for r in rows if r[1] == "无"]
hi = [r for r in yes if r[2] == "高置信"]
mid = [r for r in yes if r[2] == "中置信"]

L = []
A = L.append
A("# 桂林古本 · 校记锚点表")
A("")
A("> **本版无编者硬锚点。** 桂林古本（1980 年广西人民出版社第 2 版简体横排整理本）的"
  "整理者按语中没有「同《宋本伤寒论》第 X 条」这类直接指认，"
  "因此不存在脉经本、康平本、唐本那种「编者已核定条号」的最高置信依据。")
A("> 本表所列为**本轮（A2 第二轮）人工核定**的 36 条落点锚：每条都指定本版明文落句，"
  "可由任何人拿正文复核。证据力 **C 级**（据整理本正文核，未见影印件）。")
A("")
A("锚点类型：")
A("")
A("- **主锚** —— 宋本一条 ↔ 本版一句明文，可直接对上；")
A("- **并条锚** —— 宋本两条在本版合抄为一，本表指向合抄后的那一句；")
A("- **分条锚** —— 宋本一条在本版拆为数条，本表指向首句，其余分段见「分段」列来源文件；")
A("- **反证锚** —— 判定为「无」者，附证伪依据（检索 0 命中 / 明文相反 / 归入别篇）。")
A("")
A("---")
A("")
A("## 一、36 条落点锚总表")
A("")
A("| 宋本条号 | 状态 | 置信 | 锚句（本轮用以定位的本版句子） | 本版落点原文 | 页 | 篇 | 相似 |")
A("|---:|:--:|:--:|---|---|:--:|---|:--:|")
for no, st, cf, an, yw, pg, pian, sim in rows:
    A("| %d | %s | %s | %s | %s | %s | %s | %s |" % (no, st, cf, an, yw, pg, pian, sim))
A("")
A("**合计 36 条：有 %d（高 %d / 中 %d）、无 %d。**"
  % (len(yes), len(hi), len(mid), len(no_)))
A("")
A("「相似」为本版落点原文与宋本 398 条骨架该条正文的字符级相似度"
  "（`difflib.SequenceMatcher`，去标点）。本版与宋本异文密度高，"
  "该值只用于横向比较、不用于判「有／无」；判「有」一律以本版有明文落句为准。")
A("")
A("---")
A("")
A("## 二、条号—行号索引（供逐条翻检）")
A("")
A("| 宋本条号 | 本版行号（`版本正文/01_桂林古本伤寒杂病论.md`） | 页 |")
A("|---:|---:|:--:|")
for x in J:
    no = x["条号"]
    ln = lineno(x.get("原文", "")) if x["状态"] == "有" else 0
    A("| %d | %s | %s |" % (no, ln or "—", x.get("页", "—") if x["状态"] == "有" else "—"))
A("")
A("---")
A("")
A("## 三、并条与分条（体例差异集中处）")
A("")
A("桂林古本不分「宋本第 X 条」的界，条文以文意起止，故并、分两向都有。"
  "下列 12 条为并条或分条，是本版与宋本对不上的主要成因，不是漏抄：")
A("")
A("| 宋本条号 | 形态 | 说明 |")
A("|---:|:--:|---|")
BING = {
    22: "并条", 29: "分条", 30: "分条", 121: "并条", 129: "分条",
    174: "分条", 178: "增出", 232: "并条", 277: "并条", 279: "并条",
    307: "并条", 324: "分条",
}
for x in J:
    if x["条号"] in BING:
        A("| %d | %s | %s |" % (x["条号"], BING[x["条号"]],
                                esc(x.get("依据", "")[:120]).replace("\n", " ")))
A("")
A("其余 24 条属同条内的异文、异体、省字、增字，条界一致，不列。")
A("")
A("---")
A("")
A("## 四、唯一一条反证锚：宋本第 92 条")
A("")
A("36 条中只有第 92 条判「无」。反证链三条，全部可复核：")
A("")
A("1. 全文检索本版正文，「病发热，头痛，脉反沉」「当救其里」两串 **0 命中**；")
A("2. 本版确有一处「救里／救表」论述，但以「问曰／师曰」体例写在卷三《伤寒例》"
  "（行 623），内容只及宋本第 91 条的「身体疼痛，下利清谷」，不含 92 条「脉反沉」一层；")
A("3. 宋本 92 条方后注「强人可大附子一枚、干姜三两」是四逆汤方通注，"
  "在本版见四逆汤方后（p6，行 1402），不能当成本条正文存在的证据。")
A("")
A("判定原因归入「体例不同」：本版把这条改写成论述体并入了伤寒例，"
  "不是缺失、不是漏转。")
A("")
A("---")
A("")
A("## 五、与旧版锚点表的关系")
A("")
A("A 包（第一轮转录）的锚点表只有一句「(本版无「同《宋本》第X条」式硬锚点)」，"
  "等于没有可用锚点，36 条「暂未匹配」无从定位。本轮把这 36 条一条一条钉到本版明文句上，"
  "锚点表才第一次具备检索功能。旧表不作废，其判断（本版无编者硬锚点）依然成立且已被本表继承为第一句。")
A("")
A("> 复核方式：任取表内一条，用「锚句」列在 `版本正文/01_桂林古本伤寒杂病论.md` 中检索，"
  "应命中该行；用「本版落点原文」列复核该行文字应完全一致。两者都对不上者，即为本表错误，请回报。")
A("")

open(OUT, "w", encoding="utf-8").write("\n".join(L))
print("写成 %s" % OUT)
print("36 条：有 %d（高 %d / 中 %d）、无 %d；行号定位 %d 条成功"
      % (len(yes), len(hi), len(mid), len(no_),
         sum(1 for x in J if x["状态"] == "有" and lineno(x.get("原文", "")))))
