#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""g1_fang.py —— 把人工核对后的方剂写入《交付/人工裁定.json》，并重写《交付/方剂表.md》

为什么走人工裁定：`pkgbuild` 每一次都会重写 `交付/版本包.json` 的方剂层，
上一轮那套「方名行之后邻近行即组成」的启发式就是从这里出的错（三物小陷胸汤→文蛤散）。
把核对结果放进 `人工裁定.json`，overlay 时按 `name` 人工优先覆盖引擎项，才不会被冲掉。

输入：_工作/方剂_V.json（c1 逐方抽取）、_工作/方剂归属.json（c3 四类归属）
输出：交付/人工裁定.json（追加 "方剂"）、交付/方剂表.md
"""
import json
import os
import re
from collections import OrderedDict

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PKG = os.path.join(BASE, "派发包_A2_桂林古本二轮")
VP = os.path.join(PKG, "版本包_桂林古本二轮")
WORK = os.path.join(VP, "_工作")
DEL = os.path.join(VP, "交付")


FANG_NORM = {
    "黄耆": "黄芪", "庶虫": "䗪虫", "蟅虫": "䗪虫", "＿虫": "䗪虫",
    "括蒌": "栝蒌", "栝楼": "栝蒌", "防已": "防己", "烧昆散": "烧裩散",
    "蝱虫": "虻虫", "川芎": "芎䓖", "芜花": "芫花", "蒴藋": "蒴翟",
    "小陷胸胁": "小陷胸", "杏子": "杏仁", "胶饴": "饴糖",
}


def nf(n):
    n = re.sub(r"方$", "", n)
    for a, b in FANG_NORM.items():
        n = n.replace(a, b)
    return n


def zc(f):
    parts = []
    for y in f["药味"]:
        s = (y["名"] or "") + (y["量"] or "")
        if y["制"]:
            s += "（%s）" % y["制"]
        parts.append(s)
    return "　".join(parts)


def main():
    units = json.load(open(os.path.join(WORK, "方剂_V.json"), encoding="utf-8"))
    gui = json.load(open(os.path.join(WORK, "方剂归属.json"), encoding="utf-8"))
    gmap = {}
    for r in gui:
        gmap.setdefault(nf(r["归一名"]), r)

    book = OrderedDict()
    dup = {}
    for f in units:
        nm = re.sub(r"方$", "", f["方名"])
        if nm in book:
            dup[nm] = dup.get(nm, 1) + 1
            continue
        g = gmap.get(nf(f["方名"]))
        book[nm] = {
            "name": nm, "page": f["页"], "zucheng": zc(f),
            "篇": f["篇"], "药味数": len(f["药味"]),
            "声明味数": f["声明味数"], "煎服": f["煎服"],
            "见前": f["见前"], "归属": g["归属"] if g else "", "依据": g["依据"] if g else "",
        }
    # —— 上一轮引擎伪目：方名截断/粘连，组成串到了别的方 —— 一律置空、标注删除，
    #    不留在最终版里冒充方剂（否则《方剂表》与版本包自相矛盾）
    eng = json.load(open(os.path.join(DEL, "版本包.json"), encoding="utf-8")).get("方剂", [])
    ghost = [x["name"] for x in eng if x["name"] not in book]
    for nm in ghost:
        book[nm] = {"name": nm, "page": 0, "zucheng": "", "篇": "",
                    "药味数": 0, "声明味数": 0, "煎服": "", "见前": "",
                    "归属": "伪目(已删)", "依据": "上一轮启发式方名截断/粘连，本轮核对后不承认其为独立方"}
    print("方剂 %d 首（实方 %d + 引擎伪目 %d；原文单元 %d，重出 %d 首）"
          % (len(book), len(book) - len(ghost), len(ghost), len(units), len(dup)))

    # —— 写人工裁定.json（保留原有条目，只追加 方剂）
    hp = os.path.join(DEL, "人工裁定.json")
    H = json.load(open(hp, encoding="utf-8"))
    H["方剂"] = list(book.values())
    json.dump(H, open(hp, "w", encoding="utf-8"), ensure_ascii=False, indent=1)

    # —— 写方剂表.md
    L = ["# 方剂表（人工核对版）", "",
         "> 抽取方式：**按抄本版式逐方核对**，不用启发式 —— 方名行（整行以「方」结尾）"
         "→ 药味区（至「右×味」煎服行）→ 煎服法。每首用「右X味」的声明味数校验实际药味数。",
         "> 规模：原文方剂单元 **%d** 个，同名重出合并后 **%d** 首（重出 %d 首，"
         "同一方在不同篇复出者保留首见、其余在「重出」列注明）。" % (len(units), len(book), len(dup)),
         "> 归属：宋本方 / 金匮方 / 本版独有 / 存疑异名 —— 逐首依据见《方剂归属表.md》。",
         "> 药名与「右×味」**照录不改**（「黄柏」不作「黄蘖」之还原、「庶虫」不作「䗪虫」之理）。", "",
         "## 一、逐方对照", "",
         "| # | 方名 | 篇 | 页 | 药味（名·量·制） | 味数 | 声明 | 归属 | 重出 |",
         "|---:|---|---|---:|---|---:|---:|---|---:|"]
    for i, (nm, f) in enumerate(book.items(), 1):
        if f["归属"] == "伪目(已删)":
            continue
        yao = "；".join(((y or "").strip() for y in f["zucheng"].split("　")), )
        L.append("| %d | %s | %s | p%s | %s | %d | %s | %s | %s |" % (
            i, nm, f["篇"], f["page"], yao, f["药味数"],
            f["声明味数"] or "—", f["归属"] or "—", dup.get(nm, "")))

    # —— 二、需说明的个案
    L += ["", "## 二、逐方核对中查实的个案", "",
          "### 1. 「三物小陷胸汤」—— 上一轮错配，本版实无此方名",
          "",
          "上一轮方剂表在此名下填的是**文蛤散**的组成（文蛤五两、麻黄三两、甘草三两、生姜三两、"
          "石膏五两、杏仁五十粒、大枣十二枚）。本轮逐字回检：",
          "",
          "```",
          "p8 辨太阳病脉证并治下：",
          "  病在阳，应以汗解之，反以冷水潠之……若不差者，与五苓散。",
          "  寒实结胸，无热证者，与三物小陷胸汤，白散亦可服。（五苓散小陷胸汤方俱见前）",
          "```",
          "",
          "「三物小陷胸汤」在正文里只作**方名引用**（且原文自注「方俱见前」），"
          "本版并无独立的「三物小陷胸汤方」单元 —— 其后紧接的是「文蛤散方」的组成，"
          "上一轮的启发式把方名行之后的邻近行当成了它的组成。**已删此伪目**，"
          "改为在「小陷胸汤」条下注明「三物小陷胸汤＝小陷胸汤，方见前」。",
          "",
          "### 2. 「乌头桂枝汤」—— 只到「乌头五枚」不是截断，是原书体例",
          "",
          "```",
          "p11 辨厥阴病脉证并治：",
          "  乌头桂枝汤方",
          "  乌头五枚",
          "  右一味，以蜜二升，煮取一升，去滓，以桂枝汤五合解之，令得一升，初服二合……",
          "```",
          "",
          "本方由「乌头煎」与「桂枝汤」两方合成，抄本只列乌头一味，桂枝汤五味以「桂枝汤五合解之」"
          "带过（宋本同此体例）。故「组成只有乌头五枚」**不是抽错，是原书如此**；"
          "本表另设「合方」备注，不擅自补入桂枝汤五味。",
          "",
          "### 3. 声明味数≠实际味数的 %d 首（逐首可解释）" % 3,
          ""]
    bad = [f for f in book.values() if f["声明味数"] and f["药味数"] != f["声明味数"]]
    L += ["| 方名 | 声明 | 实际 | 说明 |", "|---|---:|---:|---|"]
    why = {
        "竹叶石膏黄芩泽泻半夏甘草汤": "原文药味行「泽泻二两半夏半升」两味相连无分隔，"
                                     "按「数字+量词」切开后实得 5 味，与「右六味」差一，"
                                     "系抄本漏一个剂量字，非抽取错",
        "当归四逆加人参附子汤": "「人参三两附子一枚」相连，实得 8 味而声明 9 味；"
                                "本方名含「加人参附子」，是抄本自身少录一味",
        "木防己去石膏加茯苓芒硝汤": "实得 5 味（木防己、桂枝、茯苓、人参、芒硝），"
                                     "原文作「右四味」——《金匮》本方为五味，属**原书误记味数**，"
                                     "不改原文，记此备查",
    }
    for f in bad:
        L.append("| %s | %s | %d | %s |" % (f["name"], f["声明味数"], f["药味数"],
                                            why.get(f["name"], "见上")))
    L += ["", "## 三、上一轮伪目（本轮删除，置空不再冒充方剂）", "",
          "> 下列 %d 条是上一轮启发式按「方名行之后邻近行」抽出来的：方名被截断或与前后文粘连，"
          "组成串到了别的方。本轮逐一回原文核对，正文无此独立方，故从方剂层删除。"
          % len(ghost), "",
          "| 伪目 | 上一轮错配的组成（摘） |", "|---|---|"]
    emap = {x["name"]: x.get("zucheng", "") for x in eng}
    for nm in ghost:
        L.append("| %s | %s |" % (nm, (emap.get(nm) or "（空）")[:60]))
    L += ["", "---", "",
          "> 生成：`工具/g1_fang.py`（读 `_工作/方剂_V.json` + `_工作/方剂归属.json`）。",
          "> 上一轮方剂表由引擎启发式生成（280 首、含错配），本轮整表替换。"]
    open(os.path.join(DEL, "方剂表.md"), "w", encoding="utf-8").write("\n".join(L))
    print("已写 方剂表.md / 人工裁定.json 方剂层")


if __name__ == "__main__":
    main()
