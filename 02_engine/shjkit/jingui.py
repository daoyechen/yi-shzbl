def classify(text):
    """返回 [(篇名, 置信, 命中词, 依据)]，按置信降序、命中数降序。"""
    t = text or ""
    out = []
    for pian, spec in JG_PIAN.items():
        hits_hi = [w for w in spec["特征"] if w in t]
        hits_mid = [w for w in spec["病名"] if w in t]
        hits_lo = [w for w in spec["通用"] if w in t]
        if hits_hi:
            out.append((pian, "高", hits_hi + hits_mid + hits_lo,
                        "命中特征词:" + "、".join(hits_hi[:3])))
        elif hits_mid:
            out.append((pian, "中", hits_mid + hits_lo,
                        "命中病名:" + "、".join(hits_mid[:3])))
        elif hits_lo:
            out.append((pian, "低", hits_lo,
                        "仅命中通用词(《伤寒论》正文亦常见),仅供人工复核"))
    order = {"高": 0, "中": 1, "低": 2}
    out.sort(key=lambda x: (order[x[1]], -len(x[2])))
    return out


def cut_pack(pkg_dir):
    """切一个版本包。返回 (版本名, 条目列表)。"""
    fin = os.path.join(pkg_dir, "交付", "最终版本包.json")
    if not os.path.exists(fin):
        fin = os.path.join(pkg_dir, "交付", "版本包.json")
    if not os.path.exists(fin):
        return None, []
    d = json.load(open(fin, encoding="utf-8"))
    name = d.get("版本名") or os.path.basename(pkg_dir)
    rows = []
    # 独有内容(《金匮》散见主要在这里)
    for u in d.get("独有", []):
        txt = u.get("文本", "")
        for pian, cf, hits, why in classify(txt):
            rows.append({
                "来源": "独有", "iid": u.get("iid"), "页": u.get("页"),
                "病种": pian, "置信": cf, "命中词": hits[:5], "依据": why,
                "文本": txt[:200],
            })
    # 命中宋本 398 条但含金匮病种者(体例差异条)
    for e in d.get("条目", []):
        if e.get("状态") != "有":
            continue
        txt = e.get("原文", "")
        for pian, cf, hits, why in classify(txt):
            if cf == "低":
                continue          # 条目侧只收高/中置信,低置信留给独有侧
            rows.append({
                "来源": "条目", "条号": e.get("条号"), "页": e.get("页"),
                "病种": pian, "置信": cf, "命中词": hits[:5], "依据": why,
                "文本": txt[:200],
            })
    return name, rows


def main():
    argv = sys.argv[1:]
    outdir = None
    if argv and argv[0] == "--输出目录":
        outdir = argv[1]; argv = argv[2:]
    dirs = [a for a in argv if os.path.isdir(a)]
    if not dirs:
        print(__doc__)
        return
    allrows = {}
    for dd in dirs:
        nm, rows = cut_pack(dd)
        if nm is None:
            print(f"  ⚠ 跳过(无版本包 json):{dd}")
            continue
        allrows[nm] = rows
        cnt = {}
        for r in rows:
            cnt[(r["病种"], r["置信"])] = cnt.get((r["病种"], r["置信"]), 0) + 1
        print(f"  ✅ {nm}: 切出 {len(rows)} 条金匮侧标注")
        for (p, c), n in sorted(cnt.items(), key=lambda x: -x[1])[:8]:
            print(f"       {p:<22}{c}  {n}")

    if outdir:
        os.makedirs(outdir, exist_ok=True)
        json.dump(allrows, open(os.path.join(outdir, "金匮侧条文索引.json"), "w",
                                encoding="utf-8"), ensure_ascii=False, indent=1)
        L = ["# 金匮侧条文索引(按病种打标)", "",
             "> 由 `shjkit/jingui` 生成。**关键词命中仅为高置信度辅助**,不直接断定归属;",
             "> 每条带命中词与判定依据,可逐条回原文复核。低置信条目仅供人工参考。", ""]
        for nm, rows in allrows.items():
            L += [f"## {nm}({len(rows)} 条标注)", ""]
            L += ["| 病种 | 置信 | 来源 | 定位 | 命中词 | 依据 |", "|---|---|---|---|---|---|"]
            for r in rows:
                loc = r.get("iid") or (f"第{r.get('条号')}条" if r.get("条号") else "")
                L.append(f"| {r['病种']} | {r['置信']} | {r['来源']} | {loc} | "
                         f"{'、'.join(r['命中词'][:3])} | {r['依据']} |")
            L.append("")
        open(os.path.join(outdir, "金匮侧条文索引.md"), "w", encoding="utf-8").write("\n".join(L))
        print(f"\n  → 已写出 {outdir}/金匮侧条文索引.{{json,md}}")


if __name__ == "__main__":
    main()
